"""The product documents, generated from reports/results.json, so every number in them is traced to
a run. Written by `dgp run`; do not edit by hand. Prose that is judgement, not measurement, lives in
config/product.yaml (problems, hypotheses, kill criteria) and is quoted from there."""

from __future__ import annotations

from typing import Any

from .. import settings


def n(x: Any, d: int = 0) -> str:
    if x is None:
        return "–"
    if isinstance(x, float) and d:
        return f"{x:,.{d}f}"
    return f"{round(x):,}" if isinstance(x, (int, float)) else str(x)


def pct(x: float | None, d: int = 1) -> str:
    return "–" if x is None else f"{x * 100:.{d}f}%"


def lc(title: str) -> str:
    """A title inside a sentence: lower the first letter unless it starts an acronym (A2A, AI)."""
    return title if title[:2].isupper() else title[0].lower() + title[1:]


def wording_share(r: dict[str, Any]) -> float:
    """Of today's wrong numbers, the share from questions worded unlike the catalogue (truth)."""
    k = r["evaluation"]["variants"]["today"]["summary"]["by_kind"]
    wrong = {kind: c.get("wrong_number", 0) for kind, c in k.items()}
    return wrong.get("paraphrase", 0) / max(1, sum(wrong.values()))


def _ci(iv: list[int] | None) -> str:
    return "" if not iv else f" ({n(iv[0])} to {n(iv[1])})"


def heldout(r: dict[str, Any]) -> list[dict[str, Any]]:
    """First runs of blind question sets, with the trust-weighted value of each configuration."""
    import json

    w = settings.load("product")["value"]["wrong_number_weight"]
    out = []
    for f in sorted((settings.REPORTS / "heldout").glob("*/first_run.json")):
        h = json.loads(f.read_text())
        cfgs = {}
        for name, c in h["configs"].items():
            res = c["results"]
            cfgs[name] = {
                "right": c["right"],
                "correct": res.get("correct", 0),
                "wrong": res.get("wrong_number", 0),
                "value": res.get("correct", 0) - w * (res.get("wrong_number", 0) + res.get("stale", 0)),
            }
        out.append({"set": h["set"], "status": h["status"], "cases": h["cases"], "configs": cfgs})
    return out


def heldout_md(r: dict[str, Any]) -> list[str]:
    sets = heldout(r)
    if not sets:
        return ["No held-out set has been run yet."]
    lines = [
        "| Set | Configuration | Right | Right numbers | Wrong numbers | Trust-weighted |",
        "|---|---|---|---|---|---|",
    ]
    for h in sets:
        for name, c in h["configs"].items():
            lines.append(
                f"| {h['set']} ({h['status']}) | {name} | {c['right']} of {h['cases']} | {c['correct']} | "
                f"{c['wrong']} | {c['value']} |"
            )
    return lines


def results_md(r: dict[str, Any]) -> str:
    o, t, ev = r["observed"], r["truth"], r["evaluation"]["variants"]
    today, none = ev["today"]["summary"], ev["no_platform"]["summary"]
    lines = [
        "# Results",
        "",
        f"Generated by `dgp run` in {r['seconds']} s. Twelve simulated weeks of a business-statistics publisher: "
        f"{len(r['scored'])} platform bets, {r['accounts']} customer accounts asking through Claude, Copilot, the research "
        f"assistant, n8n and the API. Each simulated question stands for {r['represents']} real ones.",
        "",
        "## Release gate",
        "",
        "| Check | Value | Bound | |",
        "|---|---|---|---|",
    ]
    for g in r["gate"]:
        lines.append(
            f"| {g['name']} | {n(g['value'], 4) if isinstance(g['value'], float) else g['value']} | "
            f"{g['op']} {n(g['bound'], 4) if isinstance(g['bound'], float) else g['bound']} | "
            f"{'pass' if g['passed'] else '**FAIL**'} |"
        )
    ns = o["north_star"]
    lines += [
        "",
        "## The North Star and its drivers (what the platform team sees)",
        "",
        f"**Verified answers delivered: {n(ns['estimate_per_week'])} a week**{_ci(ns['interval_per_week'])}, "
        f"estimated from analysts' audit of {n(ns['audited'])} answers ({pct(ns['accuracy_estimate'])} right). "
        f"The simulation's truth: {n(t['north_star_per_week'])} a week.",
        "",
        "| Driver | Value |",
        "|---|---|",
    ]
    d, gr = o["drivers"], o["guardrails"]
    lines += [
        f"| Sessions a week | {n(d['sessions_per_week'])} |",
        f"| Searches that found nothing | {pct(d['zero_result_share'])} |",
        f"| Sessions where the user rephrased | {pct(d['rephrased_share'])} |",
        f"| Fetches answered with a value | {pct(d['fetch_ok_share'])} |",
        f"| p95 latency | {n(gr['latency_p95_ms'])} ms |",
        f"| Platform cost a week | EUR {n(gr['cost_per_week_eur'], 2)} |",
        f"| Wrong-number tickets a week | {n(gr['wrong_number_tickets_per_week'])} |",
        "",
        "## The bets, measured",
        "",
        f"The same questions of weeks 9 to 12 through each version of the platform; differences are paired by "
        f"account (90% intervals). Value = verified answers gained minus "
        f"{settings.load('product')['value']['wrong_number_weight']} for every wrong or stale number given.",
        "",
        "| Bet | Evidence | Value a week | Verified answers | Wrong numbers | Effort (eng-weeks) | Score |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in sorted(r["scored"], key=lambda x: -x["score"]):
        lines.append(
            f"| {s['title']} | {s['evidence'].replace('_', ' ')} | {n(s['value'], 2) if s['bucket'] == 'efficiency' else n(s['value'])}"
            f"{_ci(s.get('interval'))} {'EUR' if s['bucket'] == 'efficiency' else ''} | "
            f"{n(s.get('correct_per_week'))} | {n(s.get('wrong_numbers_per_week'))} | {s['effort_weeks']} | {s['score']} |"
        )
    lines += [
        "",
        f"Without the platform an assistant answers from memory: {pct(none['wrong_number_share'])} of its answers "
        f"are wrong numbers, against {pct(today['wrong_number_share'])} with today's platform.",
        "",
        "Features already live, switched off for the same weeks:",
        "",
    ]
    for sid, sh in settings.load("product")["shipped"].items():
        v = ev[f"without_{sid}"]["delta"]
        lines.append(
            f"- **{sh['title']}**: without it, {n(v['stale']['per_week'])} more stale and "
            f"{n(v['wrong_number']['per_week'])} more wrong numbers a week."
        )
    rm, plan = r["roadmap"], r["plan"]
    lines += ["", "## Roadmap", "", "| | Bet | Why |", "|---|---|---|"]
    for col in ("now", "next", "discovery", "not_now"):
        for b in rm[col]:
            lines.append(
                f"| {col.replace('_', ' ').capitalize()} | {b['title']} | {'; '.join(b.get('why', [])) or 'highest score that fits'} |"
            )
    lines += [
        "",
        f"The Now column run together: {n(plan['delta']['value']['per_week'])} a week"
        f"{_ci([plan['delta']['value']['low'], plan['delta']['value']['high']])}, against "
        f"{n(plan['parts_sum'])} from the parts measured one by one; wrong numbers fall from "
        f"{pct(today['wrong_number_share'])} to {pct(plan['summary']['wrong_number_share'])} of answers.",
        "",
        "## Held-out questions (written blind, first run)",
        "",
        "Questions written by someone who had not seen the platform, from the public catalogue listing only, "
        "asked once through today's platform and through the planned one.",
        "",
        *heldout_md(r),
        "",
        _heldout_risk(r),
        "",
        "## Producers",
        "",
    ]
    p, ps = o["producers"], o["producers_selfserve"]
    lines += [
        f"{p['deliveries']} deliveries; {p['refused']} refused at the door "
        f"({', '.join(f'{k}: {v}' for k, v in p['refusal_reasons'].items())}). A refused revision went live after "
        f"{n(p['days_refused_to_live_median'], 1)} days (median); with contract checks in producers' CI, "
        f"{ps['refused']} reached the door and fixes went live after {n(ps['days_refused_to_live_median'], 1)} days.",
        f"Truth: the door refused exactly the deliveries that would have broken consumers: "
        f"{t['deliveries']['production']['refused_exactly_the_breaking']}.",
    ]
    return "\n".join(lines) + "\n"


def strategy_md(r: dict[str, Any]) -> str:
    p = settings.load("product")
    o, ev, rm = r["observed"], r["evaluation"]["variants"], r["roadmap"]
    today = ev["today"]["summary"]
    now = ", ".join(lc(b["title"]) for b in rm["now"])
    return f"""# Platform strategy: grounding AI answers in verified statistics

*Generated from `reports/results.json`; the judgement is in `config/product.yaml`.*

## Where we are

Customers increasingly reach our statistics through AI clients rather than our site. Today the
platform delivers about **{n(o["north_star"]["estimate_per_week"])} verified answers a week**: the right
number, from the live version, with a citation. But **{pct(today["wrong_number_share"])}** of the answers it
helps give are wrong numbers; {pct(wording_share(r), 0)} of those come from questions worded unlike our catalogue. A wrong
number carrying our citation costs more trust than a refusal. That is why the value of every bet below
counts a wrong number as {p["value"]["wrong_number_weight"]} lost answers.

## North Star

**{p["north_star"]["name"]}**: {p["north_star"]["definition"].strip()}

Drivers: questions asked → searches that find the right statistic → fetches that return a value →
right version and citation. Guardrails: wrong-number share ≤ {pct(p["guardrails"]["wrong_number_share_max"], 0)},
p95 latency ≤ {p["guardrails"]["latency_p95_ms_max"]} ms, cost per verified answer ≤ EUR
{p["guardrails"]["cost_per_correct_eur_max"]}, and no premium value reaching a plan without premium.

## This quarter

Now: {now}. Together they move the North Star value by **{n(r["plan"]["delta"]["value"]["per_week"])} a week** and cut
wrong numbers to **{pct(r["plan"]["summary"]["wrong_number_share"])}** of answers. That is measured on the same
questions, not estimated.

## What we will not do yet, and why

{chr(10).join(f"- **{b['title']}**: {'; '.join(b.get('why', []))}" for b in rm["next"] + rm["discovery"] + rm["not_now"]) or "- nothing deferred"}

## The risk we are watching

{_heldout_risk(r)}

## How we decide

A bet is scored as value × confidence ÷ effort within its investment bucket
({", ".join(f"{k.replace('_', ' ')} {v} eng-weeks" for k, v in p["capacity_engineer_weeks"].items())}). Confidence comes from
the kind of evidence: {", ".join(f"{k.replace('_', ' ')} {v}" for k, v in p["evidence_confidence"].items())}.
Every bet has a kill criterion before it starts, and the Now column is run together before we commit,
in case the parts do not add up.
"""


def _heldout_risk(r: dict[str, Any]) -> str:
    sets = heldout(r)
    if not sets:
        return "No blind question set has been run yet; the simulated vocabulary may flatter the glossary."
    h = sets[0]
    t, p = h["configs"].get("today"), h["configs"].get("plan")
    if not t or not p:
        return ""
    verdict = (
        "holds up"
        if p["value"] > t["value"]
        else "does not hold up yet: it answers more questions but also gives more wrong numbers"
    )
    return (
        f"On {h['cases']} questions written blind ({h['set']}), the plan gave {p['correct'] - t['correct']} more right "
        f"answers and {p['wrong'] - t['wrong']} more wrong numbers than today: by our own trust weighting it "
        f"{verdict}. The simulated customers' vocabulary flatters the glossary. So the glossary ships only "
        "behind analyst review and a two-week canary with its kill criterion, and the blind set is not studied: "
        "if its failures are, it becomes a regression set and a new one is written."
    )


def roadmap_md(r: dict[str, Any]) -> str:
    rm = r["roadmap"]
    out = ["# Roadmap", "", "*Generated from `reports/results.json`.*", ""]
    for col, title in (
        ("now", "Now (this quarter)"),
        ("next", "Next"),
        ("discovery", "Discovery"),
        ("not_now", "Not now"),
    ):
        out += [f"## {title}", ""]
        if not rm[col]:
            out += ["Nothing.", ""]
        for b in rm[col]:
            val = (
                f"{n(b['value'], 2)} EUR saved a week"
                if b["bucket"] == "efficiency"
                else f"{n(b['value'])} {b['unit']}{_ci(b.get('interval'))}"
            )
            out += [
                f"### {b['title']}",
                "",
                f"- **Problem**: {b['problem']}",
                f"- **Hypothesis**: {b['hypothesis']}",
                f"- **Evidence**: {b['evidence'].replace('_', ' ')}: {val}; confidence {b['confidence']}",
                f"- **Effort**: {b['effort_weeks']} engineer-weeks ({b['bucket'].replace('_', ' ')})",
                f"- **Kill criterion**: {b['kill']}",
            ]
            if b.get("why"):
                out.append(f"- **Why here**: {'; '.join(b['why'])}")
            out.append("")
    return "\n".join(out)


def prd_md(r: dict[str, Any]) -> str:
    top = max((b for b in r["roadmap"]["now"] if b["bucket"] == "north_star"), key=lambda b: b["score"])
    ev = r["evaluation"]["variants"][top["id"]]
    base = r["evaluation"]["variants"][ev.get("measured_against", "today")]["summary"]
    s = ev["summary"]
    g = r["glossary"]
    examples = "\n".join(f"| {m} | {', '.join(ws)} |" for m, ws in sorted(g["metrics"].items())[:10])
    geos = "\n".join(f"| {code} | {', '.join(ws)} |" for code, ws in sorted(g["geos"].items()))
    return f"""# PRD: {top["title"]}

*Generated from `reports/results.json`. Owner: platform product. Status: proposed for this quarter.*

## Problem
{top["problem"]}

## Evidence
Run on the questions of weeks 9 to 12, on top of {ev.get("measured_against", "today")}:

| | Before | With the glossary |
|---|---|---|
| Wrong numbers, share of answers | {pct(base["wrong_number_share"])} | {pct(s["wrong_number_share"])} |
| Questions missed (answerable, not answered) | {pct(base["missed_share"])} | {pct(s["missed_share"])} |
| Verified answers a week | {n(base["correct_per_week"])} | {n(s["correct_per_week"])} |

Value: **{n(top["value"])} trust-weighted answers a week**{_ci(top.get("interval"))}; confidence {top["confidence"]}.

## Hypothesis
{top["hypothesis"]}

## Users
- **Customers' AI clients** (Claude, Copilot, Langdock, n8n): get the statistic the user meant.
- **Analysts**: review proposed synonyms; nothing is served without their approval.
- **Platform engineers**: run the weekly mining job; own the serving index.

## Requirements
1. Mine candidate synonyms weekly from MCP session logs: rephrased queries that ended in a fetch.
2. Never propose a word the catalogue already uses, a fragment shorter than three letters, or a
   word without at least three sessions behind it. A geography name must point at one geography
   across at least three metrics.
3. Analysts approve or reject each candidate in a review queue. The approved list is versioned,
   and every change is audited.
4. Serving uses only approved words. Rolling back to the previous list takes one command.
5. No change to entitlements, citations or as-of answers.

## Acceptance criteria
- On the last four weeks, wrong-number share falls by at least a half against the current list, and
  verified answers do not fall (`dgp run`: the gate).
- p95 latency stays within {settings.load("platform")["slo"]["p95_latency_ms"]} ms.
- Every served synonym has an approving analyst and a date.

## Proposed this run (for review, not yet served)

| Metric | Words |
|---|---|
{examples}

| Geography | Names |
|---|---|
{geos}

Some proposals are wrong (a word that co-occurred by chance). That is why analysts review them.

## Rollout
Two weeks on 10% of accounts, compared with the rest on the same metrics. Then everyone.

## Kill criterion
{top["kill"]}
"""


def decisions_md(r: dict[str, Any]) -> str:
    rm = r["roadmap"]
    rows = []
    for col in ("now", "next", "discovery", "not_now"):
        for b in rm[col]:
            val = f"EUR {n(b['value'], 2)}/week" if b["bucket"] == "efficiency" else f"{n(b['value'])}/week"
            rows.append(
                f"| {b['title']} | {col.replace('_', ' ')} | {b['evidence'].replace('_', ' ')}, {val}, "
                f"confidence {b['confidence']} | {'; '.join(b.get('why', [])) or 'highest score that fits'} | "
                f"{b['kill']} |"
            )
    return (
        "# Decision log\n\n*Generated from `reports/results.json`; reversible decisions are revisited "
        "every quarter.*\n\n| Decision | Column | Evidence | Reason | Revisit / kill when |\n|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )


def brief_md(r: dict[str, Any]) -> str:
    o, plan, ev = r["observed"], r["plan"], r["evaluation"]["variants"]
    p = o["producers"]
    return f"""# Executive brief

*Generated from `reports/results.json`.*

- We deliver about **{n(o["north_star"]["estimate_per_week"])} verified answers a week** to AI clients
  (audited estimate). Without the platform, an assistant's numbers are wrong
  {pct(ev["no_platform"]["summary"]["wrong_number_share"], 0)} of the time.
- **The problem**: {pct(ev["today"]["summary"]["wrong_number_share"], 0)} of answers through the platform are still
  wrong numbers, {pct(wording_share(r), 0)} of them from questions worded unlike our catalogue. Support sees about
  {n(o["guardrails"]["wrong_number_tickets_per_week"])} wrong-number tickets a week.
- **This quarter**: {", ".join(lc(b["title"]) for b in r["roadmap"]["now"])}. Measured together:
  wrong numbers fall to {pct(plan["summary"]["wrong_number_share"])} and verified answers rise by
  {n(plan["delta"]["correct"]["per_week"])} a week.
- **Not yet**: {", ".join(lc(b["title"]) for b in r["roadmap"]["next"] + r["roadmap"]["discovery"]) or "nothing"}.
  Each has a kill criterion and a cheap test first.
- **Caution**: {_heldout_risk(r)}
- **Safety held**: no premium value reached a plan without it. The contract gate refused all
  {p["refused"]} deliveries that would have broken consumers.
"""


def write(results: dict[str, Any]) -> list[str]:
    out = settings.REPORTS
    (out / "product").mkdir(parents=True, exist_ok=True)
    files = {
        "RESULTS.md": results_md(results),
        "product/STRATEGY.md": strategy_md(results),
        "product/ROADMAP.md": roadmap_md(results),
        "product/PRD.md": prd_md(results),
        "product/DECISIONS.md": decisions_md(results),
        "product/EXEC_BRIEF.md": brief_md(results),
    }
    for name, text in files.items():
        (out / name).write_text(text)
    return sorted(files)
