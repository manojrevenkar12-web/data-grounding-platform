import type React from "react";
import { useEffect, useState } from "react";
import { type Tab, Tabs } from "./components/Tabs";
import { Bets } from "./features/bets/Bets";
import { Blind } from "./features/blind/Blind";
import { Glossary } from "./features/glossary/Glossary";
import { Overview } from "./features/overview/Overview";

const TABS: Tab[] = [
  { id: "overview", label: "Overview" },
  { id: "bets", label: "Bets" },
  { id: "blind", label: "Blind check" },
  { id: "glossary", label: "Glossary review" },
];
const VIEWS: Record<string, () => React.JSX.Element> = { overview: Overview, bets: Bets, blind: Blind, glossary: Glossary };

const fromHash = () => {
  const h = window.location.hash.replace("#", "");
  return TABS.some((t) => t.id === h) ? h : "overview";
};

export function App() {
  const [tab, setTab] = useState(fromHash);
  useEffect(() => {
    const on = () => setTab(fromHash());
    window.addEventListener("hashchange", on);
    return () => window.removeEventListener("hashchange", on);
  }, []);
  const go = (id: string) => {
    setTab(id);
    window.history.replaceState(null, "", `#${id}`);
  };
  const View = VIEWS[tab] ?? Overview;
  return (
    <div className="app">
      <a className="skip" href="#main">Skip to content</a>
      <header className="masthead">
        <p className="brand">Grounding platform <span>product review</span></p>
        <p className="masthead__scope">Verified statistics for AI clients, over twelve simulated weeks.</p>
      </header>
      <nav aria-label="Views"><Tabs tabs={TABS} current={tab} onChange={go} /></nav>
      <main id="main" role="tabpanel" aria-labelledby={`tab-${tab}`} tabIndex={-1}>
        <View />
      </main>
      <footer className="footer">
        <p>Generated by <code>dgp run</code> and <code>dgp export-web</code>. The simulation's truth scores the platform; the platform never sees it.</p>
      </footer>
    </div>
  );
}
